    private void tablaClienteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaClienteMouseClicked
        // Este es el evento al hacer clic sobre una fila de la tabla
        int fila=tablaCliente.getSelectedRow();
        if (fila==-1) {  //esta condición es para saber si la fila está seleccionada o no
            JOptionPane.showMessageDialog(this,"Debe Seleccionar una Fila");
        }//Fin del IF
        else{ // Aqui el usuario si seleccionó la tabla
            //capturo los datos que están en las posiciones de la TAbla
             this.codc = Integer.parseInt(tablaCliente.getValueAt(fila,0).toString());
             String nom= tablaCliente.getValueAt(fila,1).toString();
             String ape= tablaCliente.getValueAt(fila,2).toString();
             String dom= tablaCliente.getValueAt(fila,3).toString();
             String cor= tablaCliente.getValueAt(fila,4).toString();
             String fe= tablaCliente.getValueAt(fila,5).toString();
             String dn= tablaCliente.getValueAt(fila,6).toString();
             
             txtNombre.setText(nom);
             txtApellido.setText(ape);
             txtDomicilio.setText(dom);
             txtCorreo.setText(cor);
             txtFecha.setText(fe);
             txtDni.setText(dn);
             
        }
    }//GEN-LAST:event_tablaClienteMouseClicked

    void agregar(){
    
        String nom= txtNombre.getText();
        String ape= txtApellido.getText();
        String dom= txtDomicilio.getText();
        String cor= txtCorreo.getText();
        String fe= txtFecha.getText();
        String dn= txtDni.getText();
                
        Object[] ob=new Object[6];
        
        ob[0]= nom;
        ob[1]=ape;
        ob[2]=dom;
        ob[3]=cor;
        ob[4]=fe;
        ob[5]=dn;         
        
        cdao.add(ob);        
    }//Fin de Agregar()
    
    void actualizar(){
        String nom= txtNombre.getText();
        String ape= txtApellido.getText();
        String dom= txtDomicilio.getText();
        String cor= txtCorreo.getText();
        String fe= txtFecha.getText();
        String dn= txtDni.getText();
        //int codC= Integer.parseInt(dn)
              
        Object[] obj=new Object [6];
        
        obj[0]=dn;
        obj[1]=nom;
        obj[2]=ape;
        obj[3]=dom;
        obj[4]=cor;
        obj[5]=codc;
        
        
        cdao.actualizar(obj);
        JOptionPane.showMessageDialog(this, "Cliente Actualizado con éxito.");
        
    }//Fin de Actualizar()
    
    void eliminar(){
        int fila=tablaCliente.getSelectedRow();
        if (fila==-1){
            JOptionPane.showMessageDialog(this,"Debe seleccionar una fila");
        
        }//fin del IF
        else{
            cdao.eliminar(codc);
        
        }//fin del else
    
    }//Fin de Eliminar
    
    void nuevo(){
             txtNombre.setText("");
             txtApellido.setText("");
             txtDomicilio.setText("");
             txtCorreo.setText("");
             txtFecha.setText("");
             txtDni.setText("");
             txtDni.requestFocus();
    
    }//fin de nuevo 
    
    //Este metodo es Para limpiar los valores de la tablar al agregar clientes
    
    void limpiarTabla(){
        for (int i = 0; i < modelo.getRowCount(); i++){
            modelo.removeRow(i);;
            i=i-1;
        
        }//Fin del for
    
    }//Fin de LimpiarTabla
    
    
