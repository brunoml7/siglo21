    void listar(){
        List<Cliente> lista=cdao.listar();
        modelo=(DefaultTableModel) tablaCliente.getModel();
        Object[] ob = new Object[7];
        
        for (int i = 0; i < lista.size(); i++){
            
            Cliente cl = (Cliente) lista.get(i);
            
            ob[0]=cl.getCodCliente();
            ob[1]=cl.getNomC();
            ob[2]=cl.getApeC();
            ob[3]=cl.getDomC();
            ob[4]=cl.getCorreoC();
            ob[5]=cl.getFechaC();
            ob[6]=cl.getDniC();
            modelo.addRow(ob);
            
        
        }//fin del FOR
        
        tablaCliente.setModel(modelo);
    }//Fin de Listar

